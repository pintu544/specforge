import "dotenv/config"
import { existsSync } from "node:fs"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { basename, join, resolve } from "node:path"
import { makeBuilder } from "./participants/builder.js"
import { observer } from "./participants/observer.js"
import { operator } from "./participants/operator.js"
import { planner } from "./participants/planner.js"
import { makeReviewer } from "./participants/reviewer.js"
import { testRunner } from "./participants/testrunner.js"
import { makeTestWriter } from "./participants/testwriter.js"
import { FactoryState, initializeRuntime, join as joinParticipant, sendEvent, sendMessage } from "./runtime.js"
import { SemanticEvent } from "@mozaik-ai/core"

const TIMEOUT_MIN = Number(process.env.FACTORY_TIMEOUT_MIN ?? 25)
const TASK_STALL_MS = 8 * 60 * 1000
const IDLE_FINISH_MS = 20 * 1000

async function scaffold(outDir: string, specName: string): Promise<void> {
	await mkdir(join(outDir, "src"), { recursive: true })
	await mkdir(join(outDir, "test"), { recursive: true })
	const pkg = {
		name: "factory-output",
		version: "0.1.0",
		private: true,
		type: "module",
		scripts: {
			build: "tsc",
			// The entry module is pinned by finish() to the plan's server module
			// once the plan exists; this default covers runs that never get a plan.
			// Without a start script, `npm start` fails outright ("Missing script:
			// "start""), so an HTTP project that only builds can never be served.
			// dist/src/, not dist/: the tsconfig includes src/ and test/, so tsc
			// mirrors them under dist/ (dist/src/server.js, dist/test/...).
			start: "node dist/src/server.js",
			test: "tsc --noEmit && tsx --test test/*.test.ts",
		},
		devDependencies: {
			"@types/node": "^24.0.0",
			tsx: "^4.23.13",
			typescript: "^7.0.2",
		},
	}
	await writeFile(join(outDir, "package.json"), JSON.stringify(pkg, null, 2) + "\n")
	const tsconfig = {
		compilerOptions: {
			target: "ES2022",
			module: "NodeNext",
			moduleResolution: "NodeNext",
			strict: true,
			esModuleInterop: true,
			skipLibCheck: true,
			forceConsistentCasingInFileNames: true,
			outDir: "dist",
			types: ["node"],
		},
		include: ["src", "test"],
	}
	await writeFile(join(outDir, "tsconfig.json"), JSON.stringify(tsconfig, null, 2) + "\n")
	await writeFile(join(outDir, ".gitignore"), "node_modules/\ndist/\n")
	await writeFile(
		join(outDir, "README.md"),
		`# factory-output\n\nGenerated by SpecForge from \`${specName}\`. Run \`npm install\` then \`npm test\`.\n`,
	)
}

async function main(): Promise<void> {
	const [specArg, outArg] = process.argv.slice(2)
	if (!specArg || !outArg) {
		console.error("Usage: npm start -- <spec-file.md> <output-dir>")
		process.exit(2)
	}
	const specPath = resolve(specArg)
	const outDir = resolve(outArg)
	const specText = await readFile(specPath, "utf8")
	const specName = basename(specPath)

	await scaffold(outDir, specName)

	const initial = new FactoryState()
	initial.specText = specText
	initial.specName = specName
	initial.outDir = outDir
	initializeRuntime({ state: initial })

	const startedAt = Date.now()
	const participants = [
		operator,
		observer,
		planner,
		makeBuilder("Builder-1"),
		makeBuilder("Builder-2"),
		makeBuilder("Builder-3"),
		makeTestWriter(),
		testRunner,
		makeReviewer(),
	]
	for (const p of participants) joinParticipant(p)

	console.log(`SpecForge: building "${specName}" into ${outDir}\n`)
	sendMessage(specText, operator.getId())

	const state = initial
	let lastEventCount = 0
	let lastEventAt = Date.now()

	const watchdog = setInterval(() => {
		if (state.finished) {
			clearInterval(watchdog)
			void finish(state, startedAt, outDir)
			return
		}
		if (state.eventLog.length !== lastEventCount) {
			lastEventCount = state.eventLog.length
			lastEventAt = Date.now()
		}
		const now = Date.now()

		// Requeue or fail stalled tasks (factory self-recovery, logged).
		for (const task of state.tasks) {
			if (
				(task.status === "building" || task.status === "fixing") &&
				task.claimedAt &&
				now - task.claimedAt > TASK_STALL_MS
			) {
				if (task.status === "building" && task.fixRounds < 3) {
					task.status = "unclaimed"
					task.ownerId = undefined
					task.ownerName = undefined
					task.claimedAt = undefined
					state.log("task.requeued", "Watchdog", `task=${task.id}`)
					console.log(`[watchdog] requeued stalled task ${task.id}`)
					sendEvent(
						SemanticEvent.create("task.available", operator.getId(), { taskId: task.id }),
						operator.getId(),
					)
				} else {
					state.markFailed(task.id)
					state.log("task.failed", "Watchdog", `task=${task.id}`)
					console.log(`[watchdog] marked stalled task ${task.id} failed`)
				}
			}
		}

		const idle = now - lastEventAt > IDLE_FINISH_MS && !state.testRunning
		const anyActive = state.tasks.some((t) => t.status === "building" || t.status === "fixing")

		if (state.allBuilt() && !anyActive && idle) {
			const failed = state.tasks.filter((t) => t.status === "failed")
			const lastRun = state.testRuns[state.testRuns.length - 1]
			state.finished = true
			state.success = false
			state.finishNote =
				failed.length > 0
					? `Modules failed: ${failed.map((t) => t.id).join(", ")}.`
					: `All modules built but the run did not complete cleanly (last test run ${lastRun?.ok ? "passed" : "failed"}).`
		} else if (!state.plan && now - startedAt > TIMEOUT_MIN * 60 * 1000) {
			state.finished = true
			state.success = false
			state.finishNote = "Timed out waiting for the plan."
		} else if (now - startedAt > TIMEOUT_MIN * 60 * 1000) {
			state.finished = true
			state.success = false
			state.finishNote = `Timed out after ${TIMEOUT_MIN} minutes.`
		} else if (state.plan && now - lastEventAt > 5 * 60 * 1000 && !anyActive && !state.testRunning) {
			state.finished = true
			state.success = false
			state.finishNote = "Run stalled: no events for 5 minutes."
		}

		if (state.finished) {
			clearInterval(watchdog)
			void finish(state, startedAt, outDir)
		}
	}, 2000)
}

async function finish(state: FactoryState, startedAt: number, outDir: string): Promise<void> {
	// Pin the generated package.json's start script to the plan's actual entry
	// module (the one that starts listening), so `npm start` after `npm run
	// build` really serves the project. Prefer src/server.ts, then a module
	// whose responsibility says it starts/listens, then http/index fallbacks.
	try {
		const pkgPath = join(outDir, "package.json")
		const pkg = JSON.parse(await readFile(pkgPath, "utf8")) as {
			scripts?: Record<string, string>
		}
		const modules = state.plan?.modules ?? []
		const byPath = (suffix: string) => modules.find((m) => m.modulePath.endsWith(suffix))
		const entry =
			byPath("src/server.ts") ??
			modules.find((m) => /listen|PORT|creates the HTTP server/i.test(m.responsibility)) ??
			byPath("src/http.ts") ??
			byPath("src/index.ts")
		if (entry) {
			const base = basename(entry.modulePath, ".ts")
			pkg.scripts = { ...(pkg.scripts ?? {}), start: `node dist/src/${base}.js` }
			await writeFile(pkgPath, JSON.stringify(pkg, null, 2) + "\n")
		}
	} catch {
		// A start-script fix must never break the run summary.
	}
	const durationSec = Math.round((Date.now() - startedAt) / 1000)
	const totalIn = state.usage.reduce((a, u) => a + u.inputTokens, 0)
	const totalOut = state.usage.reduce((a, u) => a + u.outputTokens, 0)
	const summary = {
		spec: state.specName,
		project: state.plan?.projectName ?? null,
		success: state.success,
		note: state.finishNote,
		durationSec,
		humanInterventions: state.humanInterventions,
		tasks: state.tasks.map((t) => ({
			id: t.id,
			module: t.modulePath,
			owner: t.ownerName ?? null,
			status: t.status,
			fixRounds: t.fixRounds,
			reviewFixRounds: t.reviewFixRounds,
			seconds:
				t.claimedAt && t.doneAt ? Math.round((t.doneAt - t.claimedAt) / 1000) : null,
		})),
		testRuns: state.testRuns.map((r) => ({ at: r.at, ok: r.ok, tail: r.tail.slice(-600) })),
		tokens: { input: totalIn, output: totalOut },
		usageByAgent: state.usage.reduce<Record<string, { input: number; output: number; calls: number }>>(
			(acc, u) => {
				acc[u.producer] ??= { input: 0, output: 0, calls: 0 }
				acc[u.producer].input += u.inputTokens
				acc[u.producer].output += u.outputTokens
				acc[u.producer].calls += 1
				return acc
			},
			{},
		),
		events: state.eventLog,
	}
	await writeFile(join(outDir, "run-log.json"), JSON.stringify(summary, null, 2) + "\n")
	console.log("\n================ SpecForge run summary ================")
	console.log(`Result: ${state.success ? "SUCCESS" : "NOT COMPLETE"} — ${state.finishNote}`)
	console.log(`Duration: ${durationSec}s · Human interventions: ${state.humanInterventions}`)
	for (const t of summary.tasks) {
		console.log(
			`  ${t.id}: ${t.status} by ${t.owner ?? "-"} (${t.seconds ?? "?"}s, ${t.fixRounds} fix rounds)`,
		)
	}
	console.log(
		`Test runs: ${summary.testRuns.length} (${summary.testRuns.filter((r) => r.ok).length} passed)`,
	)
	console.log(`Tokens: ${totalIn} in / ${totalOut} out`)
	console.log(`Run log: ${join(outDir, "run-log.json")}`)
	console.log(`Generated project is ${existsSync(join(outDir, "src")) ? "in" : "missing from"} ${outDir}`)
	process.exit(state.success ? 0 : 1)
}

void main()
